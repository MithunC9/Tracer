import {
  LIMITS,
  REPORT_VERSION,
  type ActivityEvent,
  type AuditReport,
  type FocusSession,
  type PipelineStage,
} from '@tracer/schema';
import type { PipelineEngine, StageContext, StageInput } from './engine.js';

/**
 * Placeholder engine until `@tracer/analysis` is wired. Produces honest, minimal output:
 * real focus sessions from app_focus events, no findings, and a valid AuditReport that says so.
 */
export const stubEngine: PipelineEngine = {
  version: 'stub-1',
  async runStage(stage: PipelineStage, input: StageInput, ctx: StageContext): Promise<unknown> {
    switch (stage) {
      case 'sessionize':
        return sessionize(await input.events());
      case 'segment':
      case 'cluster':
      case 'score':
      case 'recommend':
        return [];
      case 'narrate':
        return { headline: 'No recurring workflows detected yet', body: 'The analysis engine is a placeholder in this build.' };
      case 'validate':
        return { passed: true, checkedNumbers: 0 };
      case 'publish':
        return buildReport(await input.events(), (input.outputs.sessionize as FocusSession[] | undefined) ?? [], ctx);
    }
  },
};

function sessionize(events: ActivityEvent[]): FocusSession[] {
  const out: FocusSession[] = [];
  const sorted = [...events].sort((a, b) => a.ts.localeCompare(b.ts));
  for (let i = 0; i < sorted.length; i++) {
    const e = sorted[i]!;
    if (e.kind !== 'app_focus') continue;
    const next = sorted[i + 1];
    const start = Date.parse(e.ts);
    const end = next ? Math.min(Date.parse(next.ts), start + LIMITS.idleThresholdSeconds * 1000) : start;
    out.push({
      id: `s_${e.id}`,
      appKey: e.app.key,
      urlHost: e.urlHost,
      windowTitle: e.windowTitle,
      start: new Date(start).toISOString(),
      end: new Date(end).toISOString(),
      activeSeconds: (end - start) / 1000,
      eventIds: [e.id],
      clipboardEvents: 0,
      digestText: '',
      action: 'unknown',
    });
  }
  return out;
}

function buildReport(events: ActivityEvent[], sessions: FocusSession[], ctx: StageContext): AuditReport {
  const start = Date.parse(ctx.audit.startsAt);
  const days = new Set(events.map((e) => Math.floor((Date.parse(e.ts) - start) / 86_400_000)));
  const activeSeconds = sessions.reduce((s, x) => s + x.activeSeconds, 0);
  const redactions = events.reduce((s, e) => s + Object.values(e.redactions ?? {}).reduce((a, b) => a + (b ?? 0), 0), 0);
  return {
    reportVersion: REPORT_VERSION,
    auditId: ctx.auditId,
    generatedAt: ctx.now,
    window: {
      startsAt: ctx.audit.startsAt,
      endsAt: ctx.audit.endsAt,
      daysPlanned: ctx.audit.lengthDays,
      daysObserved: days.size,
      activeHoursObserved: Math.round((activeSeconds / 3600) * 10) / 10,
      eventsAnalyzed: events.length,
      pausedMinutes: Math.round(ctx.audit.pausedSeconds / 60),
      excludedApps: ctx.exclusions.apps.length,
      excludedDomains: ctx.exclusions.domains.length,
      redactionsApplied: redactions,
    },
    summary: {
      reclaimableHoursPerWeek: 0,
      calculation: [{ label: 'Reclaimable hours per week', expression: 'no findings', value: 0, unit: 'h/week' }],
      topFindingId: null,
      narrative: { headline: 'No recurring workflows detected yet', body: 'The analysis engine is a placeholder in this build.' },
      allowedNumbers: [0],
    },
    findings: [],
    methodology: [{ title: 'Placeholder', body: 'Generated by the API stub engine; the real analysis pipeline replaces it.' }],
    limitations: ['Stub engine: sessions are counted, workflows are not yet detected.'],
    generation: {
      provider: 'none',
      model: 'stub',
      inputTokens: 0,
      outputTokens: 0,
      costUsd: 0,
      cacheHits: 0,
      validator: { passed: true, checkedNumbers: 0 },
    },
  };
}
