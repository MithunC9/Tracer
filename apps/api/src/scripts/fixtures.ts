import { existsSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ActivityEvent, GroundTruth } from '@tracer/schema';

/** Repo root (works from src/ under tsx and from dist/ when compiled). */
export function repoRoot(): string {
  let d = dirname(fileURLToPath(import.meta.url));
  for (let i = 0; i < 8; i++) {
    if (existsSync(join(d, 'pnpm-workspace.yaml'))) return d;
    d = dirname(d);
  }
  return process.cwd();
}

/** `packages/fixtures/data`, or FIXTURES_DIR. */
export function fixturesDir(): string {
  return process.env.FIXTURES_DIR ? resolve(process.env.FIXTURES_DIR) : join(repoRoot(), 'packages', 'fixtures', 'data');
}

export interface Fixture {
  persona: string;
  dir: string;
  events: ActivityEvent[];
  groundTruth: GroundTruth;
  /** RawSample JSONL for tracer-sim (generated by the fixtures build, gitignored). */
  rawPath: string;
}

export function loadFixture(persona: string): Fixture {
  const dir = join(fixturesDir(), persona);
  if (!existsSync(join(dir, 'events.json'))) throw new Error(`unknown fixture persona "${persona}" (no ${join(dir, 'events.json')})`);
  return {
    persona,
    dir,
    events: (JSON.parse(readFileSync(join(dir, 'events.json'), 'utf8')) as unknown[]).map((e) => ActivityEvent.parse(e)),
    groundTruth: GroundTruth.parse(JSON.parse(readFileSync(join(dir, 'ground-truth.json'), 'utf8'))),
    rawPath: join(dir, 'raw.jsonl'),
  };
}
