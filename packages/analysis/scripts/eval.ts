/**
 * pnpm --filter @tracer/analysis eval [--synth] [--seeds 1,2,3] [--personas a,b] [--write] [--data <dir>]
 *
 * Runs the pipeline (fallback deps) on every persona under packages/fixtures/data/* that has
 * events.json + ground-truth.json. With no fixtures (or --synth), runs on the seeded synthetic
 * personas from test/synth.ts. Prints a table; exits 1 below the recall/precision targets.
 * --write updates EVAL.md.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ActivityEvent, GroundTruth } from '@tracer/schema';
import { EVAL_TARGETS, evaluatePersona, formatTable, summarize, type PersonaEval } from '../src/eval/evaluate.js';
import { PERSONAS, synthesize } from '../test/synth.js';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, '..');
const args = process.argv.slice(2);
const flag = (f: string) => args.includes(f);
const dataDir = args.includes('--data') ? resolve(args[args.indexOf('--data') + 1]!) : resolve(pkg, '../fixtures/data');

function loadEvents(raw: unknown): ActivityEvent[] {
  const arr: unknown[] = Array.isArray(raw)
    ? raw.flatMap((x) => (x && typeof x === 'object' && 'events' in x && Array.isArray((x as { events: unknown }).events) ? (x as { events: unknown[] }).events : [x]))
    : raw && typeof raw === 'object' && 'events' in raw
      ? ((raw as { events: unknown[] }).events ?? [])
      : [];
  return arr.map((e) => ActivityEvent.parse(e));
}

// 11, 29, 47 were inspected while tuning; 101-108 are held out.
export const SYNTH_SEEDS = [11, 29, 47, 101, 102, 103, 104, 105, 106, 107, 108];

async function main() {
  const results: PersonaEval[] = [];
  let source = 'synthetic (test/synth.ts)';
  const fixtureDirs =
    !flag('--synth') && existsSync(dataDir)
      ? readdirSync(dataDir)
          .map((d) => join(dataDir, d))
          .filter((d) => existsSync(join(d, 'events.json')) && existsSync(join(d, 'ground-truth.json')))
          .filter((d) => !args.includes('--personas') || args[args.indexOf('--personas') + 1]!.split(',').some((p) => d.endsWith(`/${p}`)))
          .sort()
      : [];
  if (fixtureDirs.length) {
    source = `fixtures (${dataDir})`;
    for (const d of fixtureDirs) {
      const events = loadEvents(JSON.parse(readFileSync(join(d, 'events.json'), 'utf8')));
      const gt = GroundTruth.parse(JSON.parse(readFileSync(join(d, 'ground-truth.json'), 'utf8')));
      results.push(await evaluatePersona(events, gt));
    }
  } else {
    const seeds = args.includes('--seeds') ? args[args.indexOf('--seeds') + 1]!.split(',').map(Number) : SYNTH_SEEDS;
    for (const p of PERSONAS) for (const seed of seeds) {
      const { events, groundTruth } = synthesize(p, seed);
      results.push(await evaluatePersona(events, groundTruth));
    }
  }
  const summary = summarize(results);
  const table = formatTable(summary);
  console.log(`Source: ${source}\n`);
  console.log(table);
  const notes: string[] = [];
  for (const p of results) {
    if (p.missed.length) notes.push(`${p.persona} missed: ${p.missed.join('; ')}`);
    for (const c of p.clusters.filter((x) => !x.matched)) notes.push(`${p.persona} unmatched cluster: ${c.label} (${c.occurrences} occ, best overlap ${c.overlap})`);
  }
  for (const n of notes) console.log(`  ${n}`);
  console.log(`\nTargets: recall >= ${EVAL_TARGETS.recall}, precision >= ${EVAL_TARGETS.precision} -> ${summary.passed ? 'PASS' : 'FAIL'}`);
  if (flag('--write')) {
    const md = `# Evaluation\n\nGenerated by \`pnpm --filter @tracer/analysis eval --write\`. Source: ${source}.\n\nA reported workflow matches a planted one when at least 50% of its episodes' active time falls inside that workflow's ground-truth occurrence intervals. Recall = planted workflows matched / planted. Precision = reported workflows that match some planted workflow / reported (top ${10} findings per persona). Micro-averaged over personas.\n\n${table}\n\nTargets: recall >= ${EVAL_TARGETS.recall * 100}%, precision >= ${EVAL_TARGETS.precision * 100}%: **${summary.passed ? 'PASS' : 'FAIL'}**.\n${source.startsWith('synthetic') ? '\nSynthetic seeds 11, 29 and 47 were inspected while tuning; 101-108 were held out.\n' : ''}${notes.length ? `\n## Misses\n\n${notes.map((x) => `- ${x}`).join('\n')}\n` : ''}`;
    writeFileSync(join(pkg, 'EVAL.md'), md);
  }
  process.exit(summary.passed ? 0 : 1);
}

void main();
