#!/usr/bin/env node
// Generates src/styles/tokens.css from src/tokens.ts. Run after editing tokens.
// `--check` exits 1 if the committed CSS is stale (used by the test suite).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { color, font, grid, motion, rule, space, type, z } from '../src/tokens.ts';

const kebab = (s) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
const colorVars = (mode) =>
  Object.entries(color[mode])
    .map(([k, v]) => `  --tr-${kebab(k)}: ${v};`)
    .join('\n');

const lines = [];
lines.push('/* GENERATED by scripts/tokens.mjs from src/tokens.ts. Do not edit by hand. */');
lines.push('');
lines.push(':root {');
for (const [k, v] of Object.entries(font)) lines.push(`  --tr-font-${k}: ${v};`);
for (const [k, [size, lh, ls]] of Object.entries(type)) {
  lines.push(`  --tr-text-${kebab(k)}: ${size};`);
  lines.push(`  --tr-leading-${kebab(k)}: ${lh};`);
  lines.push(`  --tr-tracking-${kebab(k)}: ${ls};`);
}
for (const [k, v] of Object.entries(space)) lines.push(`  --tr-space-${String(k).replace('.', '_')}: ${v};`);
for (const [k, v] of Object.entries(rule)) lines.push(`  --tr-rule-${k}: ${v};`);
lines.push(`  --tr-grid-columns: ${grid.columns};`);
lines.push(`  --tr-grid-max: ${grid.maxWidth};`);
lines.push(`  --tr-grid-gutter: ${grid.gutter};`);
lines.push(`  --tr-page-margin: ${grid.pageMargin};`);
lines.push(`  --tr-measure: ${grid.measure};`);
for (const [k, v] of Object.entries(motion.duration)) lines.push(`  --tr-dur-${k}: ${v}ms;`);
for (const [k, v] of Object.entries(motion.easing)) lines.push(`  --tr-ease-${kebab(k)}: ${v};`);
lines.push(`  --tr-stagger: ${motion.stagger}ms;`);
for (const [k, v] of Object.entries(z)) lines.push(`  --tr-z-${k}: ${v};`);
lines.push('}');
lines.push('');
lines.push('/* Light: warm paper, ink. Default. */');
lines.push(':root,\n[data-theme="light"] {');
lines.push('  color-scheme: light;');
lines.push(colorVars('light'));
lines.push('}');
lines.push('');
lines.push('/* Dark: cream ink on kraft. Follows the OS unless the reader chose light. */');
lines.push('@media (prefers-color-scheme: dark) {');
lines.push('  :root:not([data-theme="light"]) {');
lines.push('    color-scheme: dark;');
lines.push(colorVars('dark').replace(/^/gm, '  '));
lines.push('  }');
lines.push('}');
lines.push('');
lines.push('[data-theme="dark"] {');
lines.push('  color-scheme: dark;');
lines.push(colorVars('dark'));
lines.push('}');
lines.push('');
lines.push('/* Print: ink on white, always. The :not(#_) bumps specificity above the dark-mode rules. */');
lines.push('@media print {');
lines.push('  :root:not(#_),\n  [data-theme]:not(#_) {');
lines.push('    color-scheme: light;');
lines.push(colorVars('print').replace(/^/gm, '  '));
lines.push('  }');
lines.push('}');
lines.push('');

const css = lines.join('\n');
const out = fileURLToPath(new URL('../src/styles/tokens.css', import.meta.url));
if (process.argv.includes('--check')) {
  const cur = readFileSync(out, 'utf8');
  if (cur !== css) {
    console.error('tokens.css is stale: run `node scripts/tokens.mjs`');
    process.exit(1);
  }
  console.log('tokens.css up to date');
} else {
  writeFileSync(out, css);
  console.log('wrote', out);
}
