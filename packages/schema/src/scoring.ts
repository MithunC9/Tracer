import { z } from 'zod';
import { RiskTag } from './apps.js';

/**
 * Scoring contract. The formula lives here (pure, tiny) so the pipeline, the report
 * validator and the web app's "show calculation" panel all use the exact same code.
 *
 *   automation_potential = 100 * (W_rep*repeatability + W_rule*rule_based_share + W_int*integration_feasibility)
 *                              * (1 - RISK_PENALTY * risk)
 *   reclaimable_hours_per_week = weekly_hours * (automation_potential / 100) * CAPTURE_RATE
 *
 * CAPTURE_RATE (< 1) is a deliberate haircut: automation never removes 100% of the time
 * (review, exceptions, setup). We state it in the methodology section.
 */
export const SCORING = {
  version: 1,
  weights: { repeatability: 0.3, ruleBasedShare: 0.35, integrationFeasibility: 0.35 },
  riskPenalty: 0.5,
  captureRate: 0.7,
  /** Clusters below this many occurrences are not reported as findings. */
  minOccurrences: 3,
  /** Weekly hours = total minutes / (calendar days observed / 7). */
  daysPerWeek: 7,
} as const;

const Unit = z.number().min(0).max(1);

export const ScoreInputs = z
  .object({
    /** Hours per week this workflow costs, = totalMinutes/60 / (calendar daysObserved / 7) */
    weeklyHours: z.number().nonnegative(),
    /** 0..1 consistency of the app/action path across occurrences */
    repeatability: Unit,
    /** 0..1 share of steps that are deterministic (copy/paste, export, form fill) vs judgement */
    ruleBasedShare: Unit,
    /** 0..1 how automation-friendly the touched apps are */
    integrationFeasibility: Unit,
    /** 0..1, higher = riskier (money movement, PII, irreversible actions) */
    risk: Unit,
    riskFlags: z.array(RiskTag),
    occurrences: z.number().int().nonnegative(),
    daysSeen: z.number().int().nonnegative(),
    daysObserved: z.number().int().positive(),
    /** 0..1 mean intra-cluster similarity */
    cohesion: Unit,
  })
  .meta({ id: 'ScoreInputs' });
export type ScoreInputs = z.infer<typeof ScoreInputs>;

export const ScoreOutputs = z
  .object({
    automationPotential: z.number().min(0).max(100),
    /** 0..1 how sure we are this is a real, recurring workflow */
    confidence: Unit,
    confidenceLabel: z.enum(['low', 'medium', 'high']),
    reclaimableHoursPerWeek: z.number().nonnegative(),
    /** One plain sentence explaining the score, generated by code (template), not the LLM. */
    why: z.string().max(240),
  })
  .meta({ id: 'ScoreOutputs' });
export type ScoreOutputs = z.infer<typeof ScoreOutputs>;

export const ScoreBreakdown = z
  .object({ inputs: ScoreInputs, outputs: ScoreOutputs, formulaVersion: z.literal(SCORING.version) })
  .meta({ id: 'ScoreBreakdown' });
export type ScoreBreakdown = z.infer<typeof ScoreBreakdown>;

export const round = (n: number, dp = 1) => {
  const f = 10 ** dp;
  return Math.round(n * f) / f;
};

export function automationPotential(i: Pick<ScoreInputs, 'repeatability' | 'ruleBasedShare' | 'integrationFeasibility' | 'risk'>): number {
  const w = SCORING.weights;
  const base = w.repeatability * i.repeatability + w.ruleBasedShare * i.ruleBasedShare + w.integrationFeasibility * i.integrationFeasibility;
  return round(100 * base * (1 - SCORING.riskPenalty * i.risk), 0);
}

export function confidence(i: Pick<ScoreInputs, 'occurrences' | 'daysSeen' | 'daysObserved' | 'cohesion'>): number {
  const occ = Math.min(1, i.occurrences / 10);
  const spread = Math.min(1, i.daysSeen / Math.max(1, Math.min(i.daysObserved, 5)));
  return round(0.4 * occ + 0.3 * spread + 0.3 * i.cohesion, 2);
}

export const confidenceLabel = (c: number) => (c >= 0.75 ? 'high' : c >= 0.5 ? 'medium' : 'low') as 'low' | 'medium' | 'high';

export function weeklyHours(totalMinutes: number, daysObserved: number): number {
  const weeks = Math.max(1, daysObserved) / SCORING.daysPerWeek;
  return round(totalMinutes / 60 / weeks, 1);
}

export function reclaimableHours(weekly: number, ap: number): number {
  return round(weekly * (ap / 100) * SCORING.captureRate, 1);
}

/** Calculation steps rendered verbatim by the web app's "how we got this number" panel. */
export const CalcStep = z
  .object({
    label: z.string(),
    expression: z.string(),
    value: z.number(),
    unit: z.string(),
    /** Convention: one 'finding' step per finding in rank order, then one 'total' step. */
    kind: z.enum(['finding', 'total', 'note']).optional(),
    findingId: z.string().optional(),
  })
  .meta({ id: 'CalcStep' });
export type CalcStep = z.infer<typeof CalcStep>;
